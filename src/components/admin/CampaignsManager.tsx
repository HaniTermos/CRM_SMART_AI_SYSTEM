import { useState } from "react";
import { useQuery, useMutation, useQueryClient } from "@tanstack/react-query";
import { api } from "@/lib/api";
import { useMyStore } from "@/lib/use-my-store";
import { Card, CardContent } from "@/components/ui/card";
import { Button } from "@/components/ui/button";
import { Badge } from "@/components/ui/badge";
import { toast } from "sonner";
import { Loader2, Plus, Send, Mail, Wand2, CheckCircle2, AlertCircle, RefreshCw, X } from "lucide-react";
import { Input } from "@/components/ui/input";
import { Textarea } from "@/components/ui/textarea";
import { Label } from "@/components/ui/label";

const SEGMENTS = ["new", "active", "vip", "at_risk", "churned"] as const;

export function CampaignsManager() {
  const { data: store } = useMyStore();
  const storeId = store?.id;
  const queryClient = useQueryClient();

  const [mode, setMode] = useState<"list" | "create" | "edit" | "ai">("list");
  const [editingId, setEditingId] = useState<string | null>(null);

  const [name, setName] = useState("");
  const [subject, setSubject] = useState("");
  const [contentHtml, setContentHtml] = useState("");
  const [targetSegment, setTargetSegment] = useState<string>("");

  const [aiPrompt, setAiPrompt] = useState("");
  const [aiSegment, setAiSegment] = useState<string>("");
  const [aiGenerated, setAiGenerated] = useState<any>(null);

  const { data: campaigns = [], isLoading } = useQuery({
    queryKey: ["campaigns", storeId],
    queryFn: async () => {
      const res = await api.get(`/campaigns/${storeId}`);
      return res.data.data;
    },
    enabled: !!storeId,
  });

  const { data: smtpStatus } = useQuery({
    queryKey: ["smtp-status", storeId],
    queryFn: async () => {
      const res = await api.get(`/campaigns/${storeId}/smtp-status`);
      return res.data.data;
    },
    enabled: !!storeId,
  });

  const createMut = useMutation({
    mutationFn: async () => {
      const res = await api.post(`/campaigns/${storeId}`, {
        name,
        subject,
        content_html: contentHtml,
        target_segment: targetSegment || null,
      });
      return res.data.data;
    },
    onSuccess: () => {
      toast.success("Campaign created");
      queryClient.invalidateQueries({ queryKey: ["campaigns", storeId] });
      goToList();
    },
    onError: (e: any) => {
      console.error("[Campaign] Create failed:", e);
      toast.error(e?.response?.data?.error || "Failed to create campaign");
    },
  });

  const updateMut = useMutation({
    mutationFn: async () => {
      const res = await api.patch(`/campaigns/${storeId}/${editingId}`, {
        name,
        subject,
        content_html: contentHtml,
        target_segment: targetSegment || null,
      });
      return res.data.data;
    },
    onSuccess: () => {
      toast.success("Campaign updated");
      queryClient.invalidateQueries({ queryKey: ["campaigns", storeId] });
      goToList();
    },
    onError: (e: any) => {
      console.error("[Campaign] Update failed:", e);
      toast.error(e?.response?.data?.error || "Failed to update campaign");
    },
  });

  const sendMut = useMutation({
    mutationFn: async (campaignId: string) => {
      const res = await api.post(`/campaigns/${storeId}/${campaignId}/send`);
      return res.data;
    },
    onSuccess: (data) => {
      toast.success(data.message || "Campaign sent");
      queryClient.invalidateQueries({ queryKey: ["campaigns", storeId] });
    },
    onError: (e: any) => {
      console.error("[Campaign] Send failed:", e);
      toast.error(e?.response?.data?.error || "Failed to send campaign");
    },
  });

  const testSmtpMut = useMutation({
    mutationFn: async () => {
      const res = await api.post(`/campaigns/${storeId}/test-smtp`, {
        to: smtpStatus?.user,
      });
      return res.data;
    },
    onSuccess: (data) => toast.success(data.message),
    onError: (e: any) => {
      console.error("[SMTP] Test failed:", e);
      toast.error(e?.response?.data?.error || "Test email failed");
    },
  });

  const aiGenMut = useMutation({
    mutationFn: async () => {
      const res = await api.post(`/ai/${storeId}/generate-campaign`, {
        description: aiPrompt,
        segment: aiSegment || null,
      });
      return res.data.data;
    },
    onSuccess: (data) => {
      setAiGenerated(data);
      toast.success("Campaign generated by AI");
    },
    onError: (e: any) => {
      console.error("[AI] Generation failed:", e);
      toast.error(e?.response?.data?.error || "AI generation failed");
    },
  });

  function goToList() {
    setMode("list");
    setEditingId(null);
    setName("");
    setSubject("");
    setContentHtml("");
    setTargetSegment("");
    setAiGenerated(null);
    setAiPrompt("");
    setAiSegment("");
  }

  function openCreate() {
    console.log("[Campaign] Opening create form");
    setEditingId(null);
    setName("");
    setSubject("");
    setContentHtml("");
    setTargetSegment("");
    setMode("create");
  }

  function openEdit(campaign: any) {
    console.log("[Campaign] Opening edit form for:", campaign.id, campaign.name);
    setEditingId(campaign.id);
    setName(campaign.name || "");
    setSubject(campaign.subject || "");
    setContentHtml(campaign.content_html || "");
    setTargetSegment(campaign.target_segment || "");
    setMode("edit");
  }

  async function saveAiCampaign() {
    console.log("[Campaign] Saving AI-generated campaign");
    if (!aiGenerated) return;
    try {
      await api.post(`/campaigns/${storeId}`, {
        name: aiGenerated.name,
        subject: aiGenerated.subject,
        content_html: aiGenerated.content_html,
        target_segment: aiGenerated.target_segment || null,
      });
      toast.success("AI campaign saved");
      queryClient.invalidateQueries({ queryKey: ["campaigns", storeId] });
      goToList();
    } catch (e: any) {
      console.error("[Campaign] AI save failed:", e);
      toast.error(e?.response?.data?.error || "Failed to save campaign");
    }
  }

  function applyAiGenerated() {
    console.log("[Campaign] Applying AI-generated to editor");
    if (!aiGenerated) return;
    setName(aiGenerated.name);
    setSubject(aiGenerated.subject);
    setContentHtml(aiGenerated.content_html);
    setTargetSegment(aiGenerated.target_segment || "");
    setMode("create");
    setAiGenerated(null);
  }

  if (!storeId) {
    return <div className="p-8 text-sm text-muted-foreground">Loading store…</div>;
  }

  if (mode === "create" || mode === "edit") {
    return (
      <div className="space-y-6">
        <div className="flex items-center justify-between">
          <h2 className="text-xl font-semibold">{mode === "edit" ? "Edit Campaign" : "New Campaign"}</h2>
          <Button variant="ghost" size="sm" onClick={goToList}>
            <X className="mr-1.5 h-4 w-4" /> Cancel
          </Button>
        </div>
        <Card>
          <CardContent className="space-y-4 p-5">
            <div className="space-y-2">
              <Label>Campaign name</Label>
              <Input value={name} onChange={(e) => setName(e.target.value)} placeholder="e.g. Summer Sale" />
            </div>
            <div className="space-y-2">
              <Label>Email subject</Label>
              <Input value={subject} onChange={(e) => setSubject(e.target.value)} placeholder="e.g. Our biggest sale of the year!" />
            </div>
            <div className="space-y-2">
              <Label>Target segment</Label>
              <select
                className="flex h-10 w-full rounded-md border border-input bg-background px-3 text-sm"
                value={targetSegment}
                onChange={(e) => setTargetSegment(e.target.value)}
              >
                <option value="">All customers</option>
                {SEGMENTS.map((s) => (
                  <option key={s} value={s}>{s}</option>
                ))}
              </select>
            </div>
            <div className="space-y-2">
              <Label>Email content (HTML)</Label>
              <Textarea
                value={contentHtml}
                onChange={(e) => setContentHtml(e.target.value)}
                rows={8}
                placeholder="<p>Hello {{name}},</p><p>...</p>"
              />
            </div>
            <div className="flex justify-end gap-2">
              <Button variant="ghost" onClick={goToList}>Cancel</Button>
              <Button
                onClick={() => {
                  console.log("[Campaign] Saving... mode:", mode);
                  mode === "edit" ? updateMut.mutate() : createMut.mutate();
                }}
                disabled={!name || !subject || (mode === "edit" ? updateMut.isPending : createMut.isPending)}
              >
                {mode === "edit"
                  ? (updateMut.isPending ? "Saving…" : "Save Changes")
                  : (createMut.isPending ? "Creating…" : "Create Campaign")}
              </Button>
            </div>
          </CardContent>
        </Card>
      </div>
    );
  }

  if (mode === "ai") {
    return (
      <div className="space-y-6">
        <div className="flex items-center justify-between">
          <h2 className="inline-flex items-center gap-2 text-xl font-semibold">
            <Wand2 className="h-5 w-5 text-primary" /> Generate Campaign with AI
          </h2>
          <Button variant="ghost" size="sm" onClick={goToList}>
            <X className="mr-1.5 h-4 w-4" /> Cancel
          </Button>
        </div>

        {!aiGenerated ? (
          <Card>
            <CardContent className="space-y-4 p-5">
              <div className="space-y-2">
                <Label>Describe your campaign</Label>
                <Textarea
                  value={aiPrompt}
                  onChange={(e) => setAiPrompt(e.target.value)}
                  rows={3}
                  placeholder="e.g. A summer clearance sale with 20% off for VIP customers, urgent tone"
                />
              </div>
              <div className="space-y-2">
                <Label>Target segment (optional)</Label>
                <select
                  className="flex h-10 w-full rounded-md border border-input bg-background px-3 text-sm"
                  value={aiSegment}
                  onChange={(e) => setAiSegment(e.target.value)}
                >
                  <option value="">All customers</option>
                  {SEGMENTS.map((s) => (
                    <option key={s} value={s}>{s}</option>
                  ))}
                </select>
              </div>
              <div className="flex justify-end gap-2">
                <Button variant="ghost" onClick={goToList}>Cancel</Button>
                <Button
                  onClick={() => {
                    console.log("[AI] Generating campaign...");
                    aiGenMut.mutate();
                  }}
                  disabled={!aiPrompt.trim() || aiGenMut.isPending}
                >
                  {aiGenMut.isPending ? <><Loader2 className="mr-2 h-4 w-4 animate-spin" /> Generating…</> : <><Wand2 className="mr-2 h-4 w-4" /> Generate</>}
                </Button>
              </div>
            </CardContent>
          </Card>
        ) : (
          <Card>
            <CardContent className="space-y-4 p-5">
              <div className="space-y-2">
                <Label>Campaign name</Label>
                <Input value={aiGenerated.name} readOnly />
              </div>
              <div className="space-y-2">
                <Label>Email subject</Label>
                <Input value={aiGenerated.subject} readOnly />
              </div>
              <div className="space-y-2">
                <Label>Target segment</Label>
                <Input value={aiGenerated.target_segment || "All customers"} readOnly />
              </div>
              <div className="space-y-2">
                <Label>Preview</Label>
                <div
                  className="rounded-md border bg-muted/30 p-3 text-sm max-w-none overflow-auto"
                  style={{ maxHeight: 300 }}
                  dangerouslySetInnerHTML={{ __html: aiGenerated.content_html }}
                />
              </div>
              <div className="flex justify-end gap-2">
                <Button variant="ghost" onClick={() => { setAiGenerated(null); setAiPrompt(""); }}>
                  <RefreshCw className="mr-1.5 h-3.5 w-3.5" /> Regenerate
                </Button>
                <Button variant="outline" onClick={applyAiGenerated}>
                  <CheckCircle2 className="mr-1.5 h-4 w-4" /> Edit first
                </Button>
                <Button onClick={() => { console.log("[AI] Saving campaign..."); saveAiCampaign(); }}>
                  <CheckCircle2 className="mr-1.5 h-4 w-4" /> Save campaign
                </Button>
              </div>
            </CardContent>
          </Card>
        )}
      </div>
    );
  }

  return (
    <div className="space-y-6">
      <div className="flex flex-wrap justify-between items-center gap-4">
        <div>
          <h2 className="text-xl font-semibold">Email Campaigns</h2>
          <p className="text-sm text-muted-foreground">Create and send email campaigns to your customers.</p>
        </div>
        <div className="flex items-center gap-2">
          <Button variant="outline" onClick={() => { console.log("[Campaign] Open AI mode"); setMode("ai"); }}>
            <Wand2 className="mr-2 h-4 w-4" /> Generate with AI
          </Button>
          <Button onClick={() => { console.log("[Campaign] Open create mode"); openCreate(); }}>
            <Plus className="mr-2 h-4 w-4" /> New Campaign
          </Button>
        </div>
      </div>

      {/* SMTP Status Banner */}
      {smtpStatus && (
        <div className={`flex items-center gap-3 rounded-lg border px-4 py-3 text-sm ${smtpStatus.enabled ? "border-green-200 bg-green-50" : "border-amber-200 bg-amber-50"}`}>
          {smtpStatus.enabled ? (
            <CheckCircle2 className="h-5 w-5 shrink-0 text-green-600" />
          ) : (
            <AlertCircle className="h-5 w-5 shrink-0 text-amber-600" />
          )}
          <div className="flex-1">
            <p className={smtpStatus.enabled ? "font-medium text-green-800" : "font-medium text-amber-800"}>
              {smtpStatus.enabled ? "SMTP is configured" : "SMTP not configured"}
            </p>
            <p className={smtpStatus.enabled ? "text-green-700" : "text-amber-700"}>
              {smtpStatus.message}
              {smtpStatus.enabled && smtpStatus.user ? ` · Sender: ${smtpStatus.user}` : ""}
            </p>
          </div>
          {smtpStatus.enabled && (
            <Button
              size="sm"
              variant="outline"
              onClick={() => {
                console.log("[SMTP] Sending test email...");
                testSmtpMut.mutate();
              }}
              disabled={testSmtpMut.isPending}
            >
              {testSmtpMut.isPending ? <Loader2 className="h-4 w-4 animate-spin" /> : <Mail className="mr-1.5 h-3.5 w-3.5" />}
              Test email
            </Button>
          )}
        </div>
      )}

      {isLoading ? (
        <div className="p-8 flex justify-center"><Loader2 className="animate-spin" /></div>
      ) : campaigns.length === 0 ? (
        <Card>
          <CardContent className="p-10 text-center text-muted-foreground">
            <Mail className="mx-auto h-8 w-8 mb-3 text-muted-foreground/60" />
            <p>No campaigns yet.</p>
            <p className="text-sm mt-1">Create your first email campaign to reach your customers.</p>
          </CardContent>
        </Card>
      ) : (
        <div className="grid gap-4">
          {campaigns.map((campaign: any) => (
            <Card key={campaign.id}>
              <CardContent className="p-5">
                <div className="flex items-start justify-between gap-4">
                  <div className="min-w-0 flex-1">
                    <div className="flex items-center gap-2 flex-wrap">
                      <h3 className="font-semibold">{campaign.name}</h3>
                      <CampaignStatusBadge status={campaign.status} />
                      {campaign.target_segment && (
                        <Badge variant="outline" className="text-xs">{campaign.target_segment}</Badge>
                      )}
                    </div>
                    <p className="text-sm text-muted-foreground mt-1 truncate">Subject: {campaign.subject}</p>
                    <div className="flex items-center gap-4 mt-3 text-xs text-muted-foreground">
                      <span>Sent: {campaign.sent_count ?? 0}</span>
                      <span>Created: {new Date(campaign.created_at).toLocaleDateString()}</span>
                    </div>
                  </div>
                  <div className="flex items-center gap-2 shrink-0">
                    <Button
                      variant="outline"
                      size="sm"
                      onClick={() => {
                        console.log("[Campaign] Edit clicked:", campaign.id);
                        openEdit(campaign);
                      }}
                    >
                      Edit
                    </Button>
                    {campaign.status !== "sending" && campaign.status !== "sent" && (
                      <Button
                        size="sm"
                        onClick={() => {
                          console.log("[Campaign] Send clicked:", campaign.id);
                          if (confirm(`Send "${campaign.name}"?`)) {
                            sendMut.mutate(campaign.id);
                          }
                        }}
                        disabled={sendMut.isPending}
                      >
                        {sendMut.isPending ? <Loader2 className="h-4 w-4 animate-spin" /> : <Send className="mr-1 h-3.5 w-3.5" />}
                        Send
                      </Button>
                    )}
                  </div>
                </div>
              </CardContent>
            </Card>
          ))}
        </div>
      )}
    </div>
  );
}

function CampaignStatusBadge({ status }: { status: string }) {
  const variantMap: Record<string, any> = {
    draft: "secondary",
    sending: "default",
    sent: "default",
    cancelled: "destructive",
  };
  return (
    <Badge variant={variantMap[status] || "secondary"} className="text-xs capitalize">
      {status}
    </Badge>
  );
}
